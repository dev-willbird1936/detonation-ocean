import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'ocean-style-prototypes/creature-roster.json');
const outputPath = path.join(root, 'ocean-style-prototypes/creature-roster-view.js');
const sourceBytes = readFileSync(sourcePath);
const roster = JSON.parse(sourceBytes.toString('utf8'));
const projection = {
  source: 'creature-roster.json',
  sourceSha256: createHash('sha256').update(sourceBytes).digest('hex'),
  depthMapping: roster.depthMapping,
  tiers: roster.tiers,
};
const contents = `// Generated by tools/build-creature-roster-view.mjs from creature-roster.json.\nwindow.OCEAN_CREATURE_ROSTER = ${JSON.stringify(projection)};\n`;

try {
  writeFileSync(outputPath, contents, { flag: 'wx' });
  process.stdout.write(`Created ${path.relative(root, outputPath)} from ${projection.sourceSha256}\n`);
} catch (error) {
  if (error.code !== 'EEXIST') throw error;
  if (readFileSync(outputPath, 'utf8') !== contents) {
    throw new Error(`Refusing to overwrite out-of-sync ${path.relative(root, outputPath)}`);
  }
  process.stdout.write(`${path.relative(root, outputPath)} is already current\n`);
}
